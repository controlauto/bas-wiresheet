"""Server-side Node-RED Admin API client.

Credentials never leave the Home Assistant backend. The client only touches
tabs generated by this integration (id derived from the sheet id, label prefix
and generator marker); any other tab is refused.
"""
from __future__ import annotations

import logging
from typing import Any

import aiohttp

from .compiler import GENERATOR, TAB_PREFIX

_LOGGER = logging.getLogger(__name__)


class NodeRedError(Exception):
    """Node-RED request failed."""


class NodeRedClient:
    def __init__(self, session: aiohttp.ClientSession, cfg: dict[str, Any]) -> None:
        self._session = session
        self._url = cfg["url"].rstrip("/")
        self._auth = cfg.get("auth", "none")
        self._username = cfg.get("username")
        self._password = cfg.get("password")
        self._verify_ssl = cfg.get("verify_ssl", True)
        self._timeout = aiohttp.ClientTimeout(total=cfg.get("timeout", 15))
        self._token: str | None = None
        self.server_id: str = cfg["ha_server_id"]
        self.name: str = cfg.get("name", "test")

    async def _headers(self) -> dict[str, str]:
        h = {"Node-RED-API-Version": "v2", "Content-Type": "application/json"}
        if self._auth == "token":
            if not self._token:
                await self._login()
            h["Authorization"] = f"Bearer {self._token}"
        return h

    def _basic(self) -> aiohttp.BasicAuth | None:
        if self._auth == "basic":
            return aiohttp.BasicAuth(self._username or "", self._password or "")
        return None

    async def _login(self) -> None:
        data = {"client_id": "node-red-admin", "grant_type": "password", "scope": "*",
                "username": self._username or "", "password": self._password or ""}
        async with self._session.post(f"{self._url}/auth/token", data=data, timeout=self._timeout, ssl=self._verify_ssl) as r:
            if r.status != 200:
                raise NodeRedError(f"Node-RED login failed (HTTP {r.status})")
            self._token = (await r.json())["access_token"]

    async def _req(self, method: str, path: str, body: Any = None, *, ok=(200, 204), allow_404=False, retry=True) -> Any:
        headers = await self._headers()
        try:
            async with self._session.request(method, f"{self._url}{path}", json=body, headers=headers, auth=self._basic(),
                                             timeout=self._timeout, ssl=self._verify_ssl) as r:
                if r.status == 401 and self._auth == "token" and retry:
                    self._token = None
                    return await self._req(method, path, body, ok=ok, allow_404=allow_404, retry=False)
                if allow_404 and r.status == 404:
                    return None
                if r.status not in ok:
                    text = (await r.text())[:300]
                    raise NodeRedError(f"Node-RED {method} {path} failed (HTTP {r.status}): {text}")
                if r.status == 204:
                    return {}
                ctype = r.headers.get("Content-Type", "")
                return await r.json() if "json" in ctype else {"text": await r.text()}
        except aiohttp.ClientError as err:
            raise NodeRedError(f"Node-RED is not reachable: {err}") from err
        except TimeoutError as err:
            raise NodeRedError("Node-RED request timed out") from err

    async def _req_typed(self, method: str, path: str, body: Any, deployment_type: str) -> Any:
        headers = await self._headers()
        headers["Node-RED-Deployment-Type"] = deployment_type
        try:
            async with self._session.request(method, f"{self._url}{path}", json=body, headers=headers, auth=self._basic(),
                                             timeout=self._timeout, ssl=self._verify_ssl) as r:
                if r.status == 409:
                    raise NodeRedError("Node-RED flows changed during deploy (revision conflict); preview again")
                if r.status not in (200, 204):
                    raise NodeRedError(f"Node-RED {method} {path} failed (HTTP {r.status}): {(await r.text())[:300]}")
                return await r.json() if r.status == 200 else {}
        except aiohttp.ClientError as err:
            raise NodeRedError(f"Node-RED is not reachable: {err}") from err

    async def info(self) -> dict:
        settings = await self._req("GET", "/settings")
        flows = await self._req("GET", "/flows")
        return {"version": settings.get("version"), "rev": flows.get("rev") if isinstance(flows, dict) else None}

    async def get_flow(self, flow_id: str) -> dict | None:
        flow = await self._req("GET", f"/flow/{flow_id}", allow_404=True)
        if flow is not None:
            _assert_generated(flow, flow_id)
        return flow

    async def put_flow(self, flow_id: str, payload: dict) -> None:
        _assert_generated(payload, flow_id)
        existing = await self._req("GET", f"/flow/{flow_id}", allow_404=True)
        if existing is None:
            # POST /flow regenerates every node id, which would break stable ids and rollback.
            # Instead append the tab to the current flow set and deploy with type "flows"
            # (only new/changed flows restart). The rev check fails the deploy if anyone
            # changed Node-RED in between; other nodes are sent back unchanged (credentials
            # are not included and are therefore preserved by Node-RED).
            cur = await self._req("GET", "/flows")
            nodes = cur["flows"]
            if any(n.get("id") == flow_id or n.get("z") == flow_id for n in nodes):
                raise NodeRedError(f"Node-RED already contains nodes for tab {flow_id}")
            new_ids = {n["id"] for n in payload["nodes"]}
            if any(n.get("id") in new_ids for n in nodes):
                raise NodeRedError("Generated node ids collide with existing Node-RED nodes")
            tab = {"id": flow_id, "type": "tab", "label": payload["label"], "disabled": payload.get("disabled", False),
                   "info": payload.get("info", ""), "env": payload.get("env", [])}
            body = {"rev": cur["rev"], "flows": nodes + [tab] + [{**n, "z": flow_id} for n in payload["nodes"]]}
            await self._req_typed("POST", "/flows", body, "flows")
        else:
            _assert_generated(existing, flow_id)
            await self._req("PUT", f"/flow/{flow_id}", payload)

    async def delete_flow(self, flow_id: str) -> None:
        existing = await self._req("GET", f"/flow/{flow_id}", allow_404=True)
        if existing is None:
            return
        _assert_generated(existing, flow_id)
        await self._req("DELETE", f"/flow/{flow_id}")


def _assert_generated(flow: dict, flow_id: str) -> None:
    """Refuse to modify anything that is not a tab generated by this integration."""
    if flow.get("id") != flow_id or not str(flow.get("label", "")).startswith(TAB_PREFIX) or GENERATOR not in str(flow.get("info", "")):
        raise NodeRedError(f"Refusing to modify Node-RED tab {flow.get('id')} ({flow.get('label')!r}): not generated by {GENERATOR}")
