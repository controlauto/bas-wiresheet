"""Compile a bas-wiresheet/1 sheet into one self-contained Node-RED tab.

The sheet schema stays independent of Node-RED: the compiler is the only place
that knows Node-RED node formats (node-red-contrib-home-assistant-websocket 0.82).

Generated tab (monitoring only, nothing is written to Home Assistant entities):
  inject "Tick 1 s" -------------------------------------------\
  server-state-changed "Sheet entities" (list) ------------------> function "Wire Sheet Runtime" -> ha-api (websocket) bas_wiresheet/push_result
  inject "Sample clock 5 s" -> api-render-template "last_reported" -/
Results go to the integration through its own websocket command (not the HA event bus),
so they are never written to the recorder database.
The function node embeds runtime.js and the sheet JSON. Node ids are derived
from the sheet id so re-deploys update the same nodes.

Why the template poll: Home Assistant updates State.last_reported in memory on every write,
including writes of an unchanged value (HA modbus writes on every scan). But over the
websocket API (a) state_reported events cannot be subscribed ("Event filter is required"),
(b) states from get_states/subscribe_entities/REST are cached serialisations whose
last_reported stays at the last change, and (c) the palette's initial states carry no
last_reported at all. The template engine reads the live State object, so
{{ states.x.y.last_reported }} is the only websocket-reachable source of new-sample arrival.
"""
from __future__ import annotations

import hashlib
import json
from pathlib import Path
from typing import Any

RUNTIME_PATH = Path(__file__).parent / "runtime" / "runtime.js"
RESULT_COMMAND = "bas_wiresheet/push_result"
CLOCK_S = 5
CLOCK_STALE_MS = 20000
TAB_PREFIX = "BAS WS - "
GENERATOR = "bas_wiresheet"
HEARTBEAT_S = 5


def stable_id(sheet_id: str, role: str) -> str:
    return hashlib.sha1(f"bas_wiresheet:{sheet_id}:{role}".encode()).hexdigest()[:16]


def tab_id(sheet_id: str) -> str:
    return stable_id(sheet_id, "tab")


def _entities(sheet: dict) -> list[str]:
    out: list[str] = []
    for b in sheet["blocks"]:
        if b["type"] == "entity_input":
            e = (b.get("params") or {}).get("entity_id")
            if e and e not in out:
                out.append(e)
    return out


def clock_template(entities: list[str]) -> str:
    """HA template returning {"<entity_id>": [state, last_reported_ms, last_changed_ms] | null}."""
    parts = []
    for e in entities:
        d, o = e.split(".", 1)
        parts.append(
            f'"{e}": {{% set s = states.{d}.{o} %}}{{% if s %}}[{{{{ s.state | tojson }}}}, '
            f'{{{{ (s.last_reported.timestamp() * 1000) | round(0) | int }}}}, {{{{ (s.last_changed.timestamp() * 1000) | round(0) | int }}}}]'
            f'{{% else %}}null{{% endif %}}'
        )
    return "{" + ", ".join(parts) + "}"


INIT_TEMPLATE = """// Generated by bas_wiresheet - do not edit in Node-RED; edit the sheet in Home Assistant.
const BasWireSheetRuntime = (function () { var module = { exports: {} }; var exports = module.exports;
/*__RUNTIME__*/
return module.exports; })();
const SHEET = /*__SHEET__*/;
const WATCH = new Set(/*__WATCH__*/);
context.set('rt', BasWireSheetRuntime.createRuntime(SHEET));
context.set('watch', WATCH);
context.set('digest', null);
context.set('last_sent', 0);
context.set('deployed_at', Date.now());
context.set('clock_ok_at', 0);
// Timer, latch and integral state survives a redeploy of the same revision (and a Node-RED restart when the
// default context store is persistent). Timers do not advance while the runtime is stopped.
const STATE_KEY = 'bas_wiresheet_state_' + SHEET.id;
const saved = global.get(STATE_KEY);
if (saved && saved.revision === SHEET.revision && saved.state) {
  const n = context.get('rt').importState(saved.state, saved.at, Date.now());
  node.status({ fill: 'blue', shape: 'ring', text: 'restored ' + n + ' timer state(s) from ' + new Date(saved.at).toISOString().slice(11, 19) });
}
context.set('state_key', STATE_KEY);
"""

FUNC_TEMPLATE = """const rt = context.get('rt');
const WATCH = context.get('watch');
const HEARTBEAT_MS = /*__HB__*/ * 1000;
if (msg.topic === 'bas_clock') {
  // Sample clock: live last_reported read through the HA template engine.
  let d = msg.payload;
  if (typeof d === 'string') { try { d = JSON.parse(d); } catch (e) { node.warn('Sample clock: bad template result'); return null; } }
  const samples = rt.samples();
  Object.keys(d || {}).forEach(id => {
    const r = d[id]; if (!r || !WATCH.has(id)) return;
    const prev = samples[id];
    rt.ingest({ entity_id: id, state: r[0], attributes: prev ? prev.attributes : {}, last_reported: r[1], last_changed: r[2] }, Date.now());
  });
  context.set('clock_ok_at', Date.now());
  return null;
}
if (msg.topic === 'bas_tick') {
  const now = Date.now();
  const clockAge = now - context.get('clock_ok_at');
  if (clockAge > /*__CLOCK_STALE__*/) rt.setTimestampSource(false, context.get('clock_ok_at') ? 'HA template sample clock not answering for ' + Math.round(clockAge / 1000) + ' s' : 'HA template sample clock not answered yet');
  else rt.setTimestampSource(true);
  const snap = rt.tick(now);
  global.set(context.get('state_key'), { revision: snap.revision, at: now, state: rt.exportState() });
  const digest = JSON.stringify(Object.keys(snap.blocks).map(k => {
    const o = snap.blocks[k].outputs; return [k, Object.keys(o).map(p => o[p] && [o[p].v, o[p].q])];
  }));
  const due = now - context.get('last_sent') >= HEARTBEAT_MS;
  if (digest === context.get('digest') && !due) return null;
  context.set('digest', digest); context.set('last_sent', now);
  const samples = rt.samples(); const telemetry = {};
  Object.keys(samples).forEach(k => { const s = samples[k]; telemetry[k] = { state: s.state, last_reported: s.last_reported, last_changed: s.last_changed, received_at: s.received_at }; });
  snap.runtime = { host: 'node-red', deployed_at: context.get('deployed_at'), telemetry: telemetry, timestamp_source: rt.timestampSource(), clock_ok_at: context.get('clock_ok_at') };
  const n = Object.keys(snap.displays).length;
  node.status({ fill: 'green', shape: 'dot', text: 'rev ' + (snap.revision || '?') + ' - ' + n + ' displays - ' + new Date(now).toISOString().slice(11, 19) });
  return { payload: { data: { type: '/*__CMD__*/', result: snap } } };
}
// state_changed: msg.data.event = {entity_id, old_state, new_state} (new_state.last_reported is current).
// Initial states emitted at deploy come from the palette's compressed state cache and carry
// no last_reported; they stay Freshness Unknown until the sample clock answers.
const ev = msg.data && (msg.data.event || msg.data);
const ns = ev && ev.new_state;
if (ns && WATCH.has(ns.entity_id)) {
  const prev = rt.samples()[ns.entity_id];
  const s = Object.assign({}, ns);
  // never move last_reported backwards (a cached state may be older than the clock reading)
  if (prev && prev.last_reported && (!s.last_reported || Date.parse(s.last_reported) < prev.last_reported)) s.last_reported = prev.last_reported;
  rt.ingest(s, Date.now());
}
return null;
"""


_runtime_cache: str | None = None


def load_runtime() -> str:
    """Cached. async_setup loads it in the executor so the event loop never reads the file."""
    global _runtime_cache
    if _runtime_cache is None:
        _runtime_cache = RUNTIME_PATH.read_text(encoding="utf-8")
    return _runtime_cache


def compile_sheet(sheet: dict, *, server_id: str, revision: int | None = None) -> list[dict[str, Any]]:
    """Return the Node-RED nodes (tab first) for the sheet."""
    if sheet.get("mode", "monitoring") != "monitoring":
        raise ValueError("Only monitoring sheets can be deployed to Node-RED")
    sid = sheet["id"]
    rev = revision if revision is not None else sheet.get("revision")
    sheet_for_rt = dict(sheet)
    sheet_for_rt["revision"] = rev
    tid = tab_id(sid)
    runtime_src = load_runtime()
    entities = _entities(sheet)
    fn_id, tick_id, st_id, sr_id, out_id, cm_id = (stable_id(sid, r) for r in ("fn", "tick", "states", "reported", "fire", "comment"))

    init = (
        INIT_TEMPLATE.replace("/*__RUNTIME__*/", runtime_src)
        .replace("/*__SHEET__*/", json.dumps(sheet_for_rt, sort_keys=True))
        .replace("/*__WATCH__*/", json.dumps(entities))
    )
    func = (FUNC_TEMPLATE.replace("/*__HB__*/", str(HEARTBEAT_S)).replace("/*__CMD__*/", RESULT_COMMAND)
            .replace("/*__CLOCK_STALE__*/", str(CLOCK_STALE_MS)))
    clk_id, tpl_id = stable_id(sid, "clock"), stable_id(sid, "template")
    info = (
        f"Generated by {GENERATOR}. sheet_id={sid} revision={rev}. Monitoring only: reads entity states and sends "
        f"results with the {RESULT_COMMAND} websocket command; writes no entities and calls no services. "
        f"Edit the sheet in Home Assistant, not here."
    )
    nodes: list[dict[str, Any]] = [
        {"id": tid, "type": "tab", "label": f"{TAB_PREFIX}{sheet['name']}", "disabled": False, "info": info,
         "env": [{"name": "BAS_WS_SHEET_ID", "value": sid, "type": "str"}, {"name": "BAS_WS_REVISION", "value": str(rev), "type": "str"}]},
        {"id": cm_id, "type": "comment", "z": tid, "name": f"{sheet['name']} - rev {rev} (generated, monitoring only)", "info": info, "x": 260, "y": 40, "wires": []},
        {"id": tick_id, "type": "inject", "z": tid, "name": "Tick 1 s", "props": [{"p": "topic", "vt": "str"}],
         "repeat": "1", "crontab": "", "once": True, "onceDelay": "2", "topic": "bas_tick", "x": 150, "y": 100, "wires": [[fn_id]]},
        {"id": st_id, "type": "server-state-changed", "z": tid, "name": "Sheet entities", "server": server_id, "version": 6,
         "outputs": 1, "exposeAsEntityConfig": "",
         "entities": {"entity": entities, "substring": [], "regex": []},
         "outputInitially": True, "stateType": "str", "ifState": "", "ifStateType": "str", "ifStateOperator": "is",
         "outputOnlyOnStateChange": False, "for": "0", "forType": "num", "forUnits": "minutes", "ignorePrevStateNull": False,
         "ignorePrevStateUnknown": False, "ignorePrevStateUnavailable": False, "ignoreCurrentStateUnknown": False,
         "ignoreCurrentStateUnavailable": False,
         "outputProperties": [{"property": "data", "propertyType": "msg", "value": "", "valueType": "eventData"}],
         "x": 160, "y": 160, "wires": [[fn_id]]},
        {"id": fn_id, "type": "function", "z": tid, "name": "Wire Sheet Runtime", "func": func, "outputs": 1, "timeout": 0,
         "noerr": 0, "initialize": init, "finalize": "", "libs": [], "x": 430, "y": 160, "wires": [[out_id]]},
        {"id": out_id, "type": "ha-api", "z": tid, "name": "Push result to HA", "server": server_id, "version": 1,
         "debugenabled": False, "protocol": "websocket", "method": "get", "path": "", "data": "", "dataType": "json",
         "responseType": "json", "outputProperties": [], "x": 690, "y": 160, "wires": [[]]},
    ]
    nodes += [
        {"id": clk_id, "type": "inject", "z": tid, "name": f"Sample clock {CLOCK_S} s", "props": [{"p": "topic", "vt": "str"}],
         "repeat": str(CLOCK_S), "crontab": "", "once": True, "onceDelay": "1", "topic": "bas_clock", "x": 160, "y": 220, "wires": [[tpl_id]]},
        {"id": tpl_id, "type": "api-render-template", "z": tid, "name": "last_reported (live)", "server": server_id, "version": 0,
         "template": clock_template(entities), "resultsLocation": "payload", "resultsLocationType": "msg",
         "templateLocation": "", "templateLocationType": "none", "x": 400, "y": 220, "wires": [[fn_id]]},
    ]
    return nodes


def to_flow_payload(nodes: list[dict]) -> dict:
    """Shape for the Node-RED Admin API /flow endpoint (a single tab)."""
    tab = nodes[0]
    return {
        "id": tab["id"],
        "label": tab["label"],
        "disabled": tab.get("disabled", False),
        "info": tab.get("info", ""),
        "env": tab.get("env", []),
        "nodes": [n for n in nodes[1:]],
    }


def diff_flows(current: dict | None, new: dict) -> dict:
    """Readable change preview between the deployed tab and the new one."""
    if current is None:
        return {"action": "create", "summary": f"Create tab {new['label']} with {len(new['nodes'])} nodes", "nodes": [
            {"id": n["id"], "name": n.get("name") or n["type"], "type": n["type"], "change": "added"} for n in new["nodes"]]}
    cur_nodes = {n["id"]: n for n in current.get("nodes", [])}
    new_nodes = {n["id"]: n for n in new["nodes"]}
    out = []
    for nid, n in new_nodes.items():
        if nid not in cur_nodes:
            out.append({"id": nid, "name": n.get("name") or n["type"], "type": n["type"], "change": "added"})
        else:
            c = cur_nodes[nid]
            keys = sorted(k for k in set(c) | set(n) if k not in ("x", "y", "z", "wires") and c.get(k) != n.get(k))
            if c.get("wires") != n.get("wires"):
                keys.append("wires")
            if keys:
                out.append({"id": nid, "name": n.get("name") or n["type"], "type": n["type"], "change": "modified", "fields": keys})
    for nid, c in cur_nodes.items():
        if nid not in new_nodes:
            out.append({"id": nid, "name": c.get("name") or c.get("type"), "type": c.get("type"), "change": "removed"})
    label_change = current.get("label") != new["label"]
    return {"action": "update", "summary": f"{len(out)} node change(s)" + (", tab renamed" if label_change else ""), "nodes": out}
